// T122 (6 Oct 2026) — battery of questions across Mishkat's themes after the voice / facts / encyclopedia work:
// the page-faithful pipeline (eval/rag1000/pipeline.mjs) on each question; one line per question in rows.jsonl and a
// readable report REPORT.md (what the visitor would see first: verified answer, tool, verses, encyclopedia, Sunnah…).
//   CF_ACCOUNT=<id> node eval/t122/run.mjs [--only k1,k2]
import { readFileSync, writeFileSync, appendFileSync, existsSync } from 'node:fs';

const HERE = new URL('./', import.meta.url);
const Q = JSON.parse(readFileSync(new URL('questions.json', HERE), 'utf8')).items;
const only = process.argv.includes('--only') ? new Set(process.argv[process.argv.indexOf('--only') + 1].split(',')) : null;
const OUT = new URL('rows.jsonl', HERE);
const done = new Map(existsSync(OUT) ? readFileSync(OUT, 'utf8').split(/\r?\n/).filter(Boolean).map(l => JSON.parse(l)).map(r => [r.k, r]) : []);
const { runQuestion } = await import('../rag1000/pipeline.mjs');

for (const it of Q) {
  if ((only && !only.has(it.k)) || (!only && done.has(it.k))) continue;
  const t0 = Date.now();
  let row;
  try { row = await runQuestion(it.q); } catch (e) { row = { error: String(e.message || e) }; }
  const out = { k: it.k, theme: it.theme, q: it.q, expect: it.expect, ms: Date.now() - t0, route: row.route, type: row.type, reason: row.reason || null,
    fact: row.fact || null, factAnswer: row.answer && typeof row.answer === 'string' ? row.answer : null, tool: row.tool || null, card: row.card || null,
    verses: row.verses || [], aiVerses: row.aiVerses || [], hadiths: Array.isArray(row.hadiths) ? row.hadiths : [], rag: row.rag || null,
    points: (row.points || []).map(p => p.items.map(x => `${x.kind}:${(x.ref || x.id || '')} ${String(x.text).slice(0, 80)}`)),
    fiqh: (row.fiqh || []).map(f => f.title), encyc: row.encyc || null, error: row.error || null };
  done.set(it.k, out);
  appendFileSync(OUT, JSON.stringify(out) + '\n');
  console.log(it.k, out.route, out.type, out.fact || out.tool || '', `v=${out.verses.length}`, out.encyc ? out.encyc.map(e => `${e.enc}:${e.items.length}`).join(',') : '', `h=${out.hadiths.length}`, out.rag || '', `${out.ms}ms`);
}

// report
const rows = Q.map(it => done.get(it.k)).filter(Boolean);
const first = (r) => r.fact ? `✓ verified answer — ${r.factAnswer}` : r.tool ? `🛠 tool «${r.tool}»` : r.card ? `card «${r.card}»` : r.type === 'abstain' && r.reason === 'ruling' ? `⚠ ruling → fiqh encyclopedia: ${r.fiqh.join(' / ') || '(none)'}`
  : r.verses.length ? `verses ${r.verses.slice(0, 5).join(' ')}` : r.type;
const lines = ['# T122 — battery across the themes of Mishkat (6 Oct 2026)', '', `Generated by \`node eval/t122/run.mjs\` (page-faithful pipeline). ${rows.length} questions.`, '',
  '| # | theme | question | what comes first | encyclopedia | Sunnah | short answer |', '|---|---|---|---|---|---|---|',
  ...rows.map(r => `| ${r.k} | ${r.theme} | ${r.q} | ${first(r).replace(/\|/g, '/')} | ${(r.encyc || []).map(e => `${e.enc}: ${e.items.map(x => x.title).join(' / ').slice(0, 120) || '—'}`).join('<br>').replace(/\|/g, '/')} | ${r.hadiths.length || ''} | ${r.rag || ''} |`)];
writeFileSync(new URL('REPORT.md', HERE), lines.join('\n') + '\n');
