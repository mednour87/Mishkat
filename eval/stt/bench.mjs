// Speech-to-text benchmark (6 Oct 2026): every audio of eval/stt/audio is sent to each engine; a result counts
// as RIGHT when every key word of the item is heard (normalised), EMPTY when nothing comes back.
//   node eval/stt/bench.mjs [engine,engine…]      engines: current, groq-v3, scribe1, scribe2, mishkat
//   writes eval/stt/RESULTS.md and eval/stt/results.json
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transcribe } from '../../functions/_lib/selector.js';

const HERE = fileURLToPath(new URL('.', import.meta.url));
const ROOT = join(HERE, '..', '..');
const env = {};
for (const line of readFileSync(join(ROOT, '.dev.vars'), 'utf8').split(/\r?\n/)) { const m = line.match(/^\s*([A-Z_0-9]+)\s*=\s*"?(.*?)"?\s*$/); if (m) env[m[1]] = m[2]; }
const ITEMS = JSON.parse(readFileSync(join(HERE, 'items.json'), 'utf8')).items;
const ENGINES = (process.argv[2] || 'current,groq-v3,scribe1,scribe2').split(',');

export const normWords = (s) => String(s).toLowerCase().replace(/[ً-ْٰـۖ-ۭ]/g, '').replace(/[أإآٱ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي')
  .replace(/[^ء-يa-z0-9\s]/g, ' ').split(/\s+/).filter(Boolean);

const blobOf = (it) => new Blob([readFileSync(join(HERE, 'audio', it.id + '.webm'))], { type: 'audio/webm' });
const groq = async (it, model) => {
  const fd = new FormData();
  fd.append('file', blobOf(it), 'speech.webm'); fd.append('model', model); fd.append('language', it.lang || 'ar');
  fd.append('response_format', 'json'); fd.append('temperature', '0');
  const r = await fetch('https://api.groq.com/openai/v1/audio/transcriptions', { method: 'POST', headers: { authorization: 'Bearer ' + env.GROQ_API_KEY }, body: fd });
  if (!r.ok) throw new Error('HTTP ' + r.status + ' ' + (await r.text()).slice(0, 120));
  return (await r.json()).text || '';
};
const scribe = async (it, model) => {
  const fd = new FormData();
  fd.append('file', blobOf(it), 'speech.webm'); fd.append('model_id', model); fd.append('language_code', it.lang === 'en' ? 'en' : 'ar');
  fd.append('tag_audio_events', 'false');
  const r = await fetch('https://api.elevenlabs.io/v1/speech-to-text', { method: 'POST', headers: { 'xi-api-key': env.ELEVENLABS_API_KEY }, body: fd });
  if (!r.ok) throw new Error('HTTP ' + r.status + ' ' + (await r.text()).slice(0, 160));
  return (await r.json()).text || '';
};
const RUN = {
  current: async (it) => { const o = await transcribe(blobOf(it), it.lang || 'ar', { GROQ_API_KEY: env.GROQ_API_KEY }, fetch, it.mode || 'search'); if (!o.ok) throw new Error(o.error); return o.text; },
  mishkat: async (it) => { const o = await transcribe(blobOf(it), it.lang || 'ar', env, fetch, it.mode || 'search'); if (!o.ok) throw new Error(o.error); return o.text + (o.via ? `  [${o.via}]` : ''); },
  'groq-v3': (it) => groq(it, 'whisper-large-v3'),
  'groq-turbo': (it) => groq(it, 'whisper-large-v3-turbo'),
  scribe1: (it) => scribe(it, 'scribe_v1'),
  scribe2: (it) => scribe(it, 'scribe_v2'),
};

const out = existsSync(join(HERE, 'results.json')) ? JSON.parse(readFileSync(join(HERE, 'results.json'), 'utf8')) : {};
for (const eng of ENGINES) {
  out[eng] = { at: new Date().toISOString(), rows: [] };
  let right = 0, empty = 0, ms = 0;
  for (const it of ITEMS) {
    const t0 = Date.now(); let text = '', error = null;
    try { text = await RUN[eng](it); } catch (e) { error = String(e.message || e); }
    const dt = Date.now() - t0; ms += dt;
    const got = new Set(normWords(text)), miss = it.key.map(k => normWords(k)[0]).filter(k => !got.has(k) && !normWords(text).some(w => w.endsWith(k) && w.length <= k.length + 2));
    const ok = !error && !miss.length; right += ok; empty += !text.trim();
    out[eng].rows.push({ id: it.id, text, ok, miss, error, ms: dt });
    console.log(eng.padEnd(8), it.id, ok ? 'OK ' : 'BAD', `${dt}ms`, error || text, miss.length ? '— missed ' + miss.join(' ') : '');
    if (eng.startsWith('groq') || eng === 'current') await new Promise(r => setTimeout(r, 3300));   // Groq free tier: 20 requests per minute
  }
  Object.assign(out[eng], { right, empty, n: ITEMS.length, meanMs: Math.round(ms / ITEMS.length) });
  console.log(`== ${eng}: ${right}/${ITEMS.length} right, ${empty} empty, mean ${Math.round(ms / ITEMS.length)} ms`);
}
writeFileSync(join(HERE, 'results.json'), JSON.stringify(out, null, 1));
const md = ['# Speech-to-text benchmark', '', `Generated by \`node eval/stt/bench.mjs\` — ${ITEMS.length} spoken questions (${new Set(ITEMS.map(i => i.voice.slice(0, 5))).size} accents, microphone-like degradation: late start, pink noise, 16 kHz Opus 24 kb/s). RIGHT = every key word heard.`, '',
  '| engine | right | empty | mean latency |', '|---|---|---|---|',
  ...Object.entries(out).map(([k, v]) => `| ${k} | ${v.right}/${v.n} | ${v.empty} | ${v.meanMs} ms |`), '',
  '## Misses', '', ...Object.entries(out).flatMap(([k, v]) => v.rows.filter(r => !r.ok).map(r => `- **${k}** ${r.id}: «${r.text || r.error || ''}» (missed: ${r.miss.join(', ')})`))];
writeFileSync(join(HERE, 'RESULTS.md'), md.join('\n') + '\n');
